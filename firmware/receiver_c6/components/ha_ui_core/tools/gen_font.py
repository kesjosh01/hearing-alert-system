#!/usr/bin/env python3
"""Generate the C6 UI glyph bitmaps (4-bit alpha) used by ha_gfx.

Only the characters the screens actually print are generated, at four sizes.
Source font: NanumSquareRound Bold (Ubuntu package fonts-nanum),
Copyright (c) 2010 NAVER Corporation, SIL Open Font License 1.1. The generated
bitmaps are a derivative of that font and stay under OFL-1.1 (see the header
written into the output file). The reserved font name is not used for them.

Usage (from the repository root):
    python3 firmware/receiver_c6/components/ha_ui_core/tools/gen_font.py
Re-run whenever a screen needs a character that is not in GLYPH_SETS; the
firmware draws a missing character as an empty advance and logs nothing.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/nanum/NanumSquareRoundB.ttf"

# name: (pixel size, characters). Sizes chosen to match the demo's
# unifont x2 / x3 / x4 text and its x6 clock digits in ink height.
GLYPH_SETS = {
    "small": (34, " 0123456789%-월일화수목금토시간없음"),
    "medium": (54, "초인종"),
    "large": (70, "긴급"),
    "clock": (66, "0123456789:-"),
}

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_C = os.path.join(HERE, "..", "src", "ha_font_data.c")

HEADER = """/*
 * GENERATED by tools/gen_font.py - do not edit by hand.
 *
 * 4-bit alpha glyph bitmaps rasterised from NanumSquareRound Bold.
 * Copyright (c) 2010, NAVER Corporation (http://www.nhncorp.com).
 * This data is licensed under the SIL Open Font License, Version 1.1
 * (https://openfontlicense.org). It is not the original font software and
 * does not use its Reserved Font Names.
 */
#include "ha_font.h"
"""


def glyph(font, ch):
    adv = int(round(font.getlength(ch)))
    if ch == " ":
        return dict(cp=ord(ch), w=0, h=0, xo=0, yo=0, adv=adv, data=[])
    # Render on a generous canvas with a known pen origin, then crop to the
    # real ink so text can be centred on what is visible (like the demo).
    size = font.size
    ox, oy = size, size * 2
    canvas = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    if not box:
        return dict(cp=ord(ch), w=0, h=0, xo=0, yo=0, adv=adv, data=[])
    l, t, r, b = box
    img = canvas.crop(box)
    w, h = r - l, b - t
    px = list(img.getdata())
    nib = [min(15, (v + 8) // 17) for v in px]
    if len(nib) % 2:
        nib.append(0)
    data = [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]
    return dict(cp=ord(ch), w=w, h=h, xo=l - ox, yo=t - oy, adv=adv, data=data)


def main():
    if not os.path.exists(FONT_PATH):
        sys.exit(f"font not found: {FONT_PATH} (apt install fonts-nanum)")
    out = [HEADER]
    total = 0
    for name, (size, chars) in GLYPH_SETS.items():
        font = ImageFont.truetype(FONT_PATH, size)
        gs = sorted((glyph(font, c) for c in dict.fromkeys(chars)), key=lambda g: g["cp"])
        bits, rows, off = [], [], 0
        for g in gs:
            rows.append(f"    {{0x{g['cp']:04X}, {off}u, {g['w']}, {g['h']}, {g['xo']}, {g['yo']}, {g['adv']}}},")
            bits.extend(g["data"])
            off += len(g["data"])
        total += off
        out.append(f"\n/* size {size}px: {''.join(chr(g['cp']) for g in gs)!r} */")
        out.append(f"static const uint8_t k_bits_{name}[{max(1, len(bits))}] = {{")
        for i in range(0, len(bits), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const ha_glyph_t k_glyphs_{name}[{len(gs)}] = {{")
        out.extend(rows)
        out.append("};")
        out.append(f"const ha_font_t ha_font_{name} = {{k_glyphs_{name}, {len(gs)}, k_bits_{name}}};")
    with open(OUT_C, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT_C)} ({total} bitmap bytes)")


if __name__ == "__main__":
    main()
