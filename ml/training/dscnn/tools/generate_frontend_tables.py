"""Generate deterministic sparse Mel/Hann/FFT tables from the Python frontend."""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dscnn_baseline.common import REPO, source
from dscnn_baseline.frontend import LogMel


def content():
    frontend = LogMel()
    arrays = {"kHann": ("float", frontend.hann),
              "kCos": ("float", np.cos(-2 * np.pi * np.arange(256) / 512).astype(np.float32)),
              "kSin": ("float", np.sin(-2 * np.pi * np.arange(256) / 512).astype(np.float32))}
    weights, bins, offsets = [], [], [0]
    for row in frontend.mel:
        indices = np.flatnonzero(row)
        bins.extend(indices)
        weights.extend(row[indices])
        offsets.append(len(weights))
    arrays.update(kOffsets=("uint16_t", offsets), kFftBins=("uint16_t", bins), kMelWeights=("float", weights))
    text = ["// Generated by tools/generate_frontend_tables.py. Do not hand edit.",
            f"// Frontend configuration SHA256: {source.fingerprint(frontend.options)}",
            "#pragma once", "#include <cstdint>", "namespace hearing { namespace tables {",
            f'constexpr char kFrontendSha256[] = "{source.fingerprint(frontend.options)}";',
            f'constexpr float kLogFloor = {frontend.options["log_floor"]:.9g}f;']
    for name, (dtype, values) in arrays.items():
        text.append(f"static constexpr {dtype} {name}[{len(values)}] = {{")
        for i in range(0, len(values), 8):
            formatted = []
            for v in values[i:i + 8]:
                if dtype == "float":
                    s = f"{float(v):.9g}"
                    if "." not in s and "e" not in s:
                        s += ".0"
                    formatted.append(s + "f")
                else:
                    formatted.append(str(int(v)))
            text.append("  " + ", ".join(formatted) + ",")
        text.append("};")
    text.extend(["} }  // namespace hearing::tables", ""])
    return "\n".join(text)


def main():
    destination = REPO / "firmware/transmitter_s3/dscnn/include/frontend_tables.h"
    value = content()
    if "--check" in sys.argv:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != value:
            raise SystemExit("Firmware frontend tables are stale")
        print("FRONTEND_TABLES_MATCH")
    else:
        destination.write_text(value, encoding="utf-8")
        print(destination)


if __name__ == "__main__":
    main()
